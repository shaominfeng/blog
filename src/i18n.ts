/** 某一语言的站点前缀：中文 /blog，英文 /blog/en */
export const basePath = (lang: Lang) => (lang === 'en' ? SITE.base + '/en' : SITE.base);

/** 从 URL 判断当前语言 */
export const langFromPath = (pathname: string): Lang =>
  pathname.startsWith(SITE.base + '/en/') || pathname === SITE.base + '/en' ? 'en' : 'zh';

